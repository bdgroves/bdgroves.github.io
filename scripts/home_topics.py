"""
Homepage topic cards, built from the post list in tags.html.

    python3 scripts/home_topics.py

Reads POSTS from tags.html and the topic definitions in data/topics.json.
Each post belongs to the first topic that shares one of its tags. Writes:
  * index.html, between <!-- TOPICS:START --> and <!-- TOPICS:END -->:
    one card per topic (image, count, newest two titles, a link to its
    topic page); and between <!-- LATEST:START/END -->, the newest post
  * tags.html, between /* TOPICS:START */ and /* TOPICS:END */: the topic
    definitions, so tags.html#topic=<id> lists exactly what the card counted

The Home topics workflow runs this whenever tags.html or data/topics.json
changes, so adding a post to tags.html is all it takes.
"""
from __future__ import annotations

import html
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent


def posts():
    s = (ROOT / "tags.html").read_text(encoding="utf-8")
    a = s.index("const POSTS = [")
    b = s.index("];", a)
    return json.loads(s[a + len("const POSTS = "):b + 1])


def topic_of(post, topics, fallback):
    tags = set(post["tags"])
    for t in topics:
        if tags & set(t["tags"]):
            return t["id"]
    return fallback


def strip_icon(title: str) -> str:
    """Titles start with an emoji; the card already has one."""
    return re.sub(r"^[^\w\"'“‘(]+", "", title).strip()


def local(url: str) -> str:
    return url.replace("https://brooksgroves.com", "") or "/"


def esc(s):
    return html.escape(s, quote=True)


def build():
    cfg = json.loads((ROOT / "data/topics.json").read_text(encoding="utf-8"))
    topics, fallback = cfg["topics"], cfg.get("fallback", cfg["topics"][-1]["id"])
    hidden = tuple("https://" + h for h in cfg.get("exclude_hosts", []))
    skip = set(cfg.get("exclude_urls", []))
    ps = [p for p in posts() if not p["url"].startswith(hidden) and p["url"] not in skip]   # gated sites stay off
    groups = {t["id"]: [] for t in topics}
    for p in ps:                                     # POSTS is newest first
        groups[topic_of(p, topics, fallback)].append(p)

    newest = ps[0]
    # Latest writing: the four newest posts as image cards (the picture is the
    # same one the post's Keep-reading card uses; none = its emoji).
    from keep_reading import IMAGE_OVERRIDES, card_image, page_file, pretty_date, icon_of
    cards = []
    for p in ps[:4]:
        img = IMAGE_OVERRIDES.get(local(p["url"])) or card_image(page_file(p["url"]), p["url"])
        media = (f'<img src="{esc(img)}" alt="" loading="lazy" decoding="async">' if img
                 else f'<span class="lw-noimg" aria-hidden="true">{esc(icon_of(p["title"]) or "✦")}</span>')
        cards.append(f'        <a class="lw-card" href="{esc(local(p["url"]))}"><span class="lw-media">{media}</span>'
                     f'<span class="lw-date">{esc(pretty_date(p["date"]))}</span>'
                     f'<span class="lw-title">{esc(p["title"])}</span>'
                     f'<span class="lw-dek">{esc(p["dek"])}</span></a>')
    latest = "\n".join(['<!-- LATEST:START (generated by scripts/home_topics.py) -->',
                        '      <div class="lw-grid">', *cards, '      </div>',
                        '      <!-- LATEST:END -->'])
    out = ['<!-- TOPICS:START (generated by scripts/home_topics.py; edit data/topics.json) -->',
           '      <div class="topic-grid">']
    order = sorted(topics, key=lambda t: -len(groups[t["id"]]))
    for t in order:
        g = groups[t["id"]]
        if not g:
            continue
        items = "".join(
            f'<li><a href="{esc(local(p["url"]))}">{esc(strip_icon(p["title"]))}</a></li>' for p in g[:2])
        n = len(g)
        out += [
            f'        <section class="topic-card" aria-labelledby="topic-{t["id"]}">',
            *([f'          <a class="topic-media" href="/topics/{t["id"]}/" tabindex="-1" aria-hidden="true">'
               f'<img class="topic-img" src="{esc(t["img"])}" alt="" loading="lazy" decoding="async"></a>']
              if t.get("img") else []),
            f'          <h3 class="topic-name" id="topic-{t["id"]}"><span class="topic-icon" aria-hidden="true">{t["icon"]}</span><a href="/topics/{t["id"]}/">{esc(t["name"])}</a></h3>',
            f'          <p class="topic-blurb">{esc(t["blurb"])}</p>',
            f'          <ul class="topic-latest">{items}</ul>',
            f'          <a class="topic-all" href="/topics/{t["id"]}/">All {n} {"entry" if n == 1 else "entries"} &rarr;</a>',
            '        </section>']
    out += ['      </div>', '      <!-- TOPICS:END -->']
    block = "\n".join(out)

    idx = ROOT / "index.html"
    s = idx.read_text(encoding="utf-8")
    s2 = re.sub(r"<!-- TOPICS:START.*?<!-- TOPICS:END -->", lambda m: block, s, flags=re.S)
    s2 = re.sub(r"<!-- LATEST:START.*?<!-- LATEST:END -->", lambda m: latest, s2, flags=re.S)
    if s2 == s and "TOPICS:START" not in s:
        raise SystemExit("index.html has no TOPICS markers")
    idx.write_text(s2, encoding="utf-8")

    tg = ROOT / "tags.html"
    s = tg.read_text(encoding="utf-8")
    js = ("/* TOPICS:START (generated by scripts/home_topics.py) */\nconst TOPICS = "
          + json.dumps([{k: t[k] for k in ("id", "name", "tags")} for t in topics], ensure_ascii=False)
          + f";\nconst TOPIC_FALLBACK = {json.dumps(fallback)};\n"
          + f"const TOPIC_HIDDEN = {json.dumps(list(hidden))};\n"
          + f"const TOPIC_SKIP = {json.dumps(sorted(skip))};\n/* TOPICS:END */")
    s2 = re.sub(r"/\* TOPICS:START.*?/\* TOPICS:END \*/", lambda m: js, s, flags=re.S)
    tg.write_text(s2, encoding="utf-8")
    print(", ".join(f"{t['name']} {len(groups[t['id']])}" for t in order), f"| {len(ps)} posts")


if __name__ == "__main__":
    build()
