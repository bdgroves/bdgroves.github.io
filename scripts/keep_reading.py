def page_file(url: str) -> Path | None:
    if url.startswith("/"):                          # some POSTS urls are site-relative
        url = SITE + url
    if not url.startswith(SITE + "/"):
        return None
    rel = local(url).lstrip("/")
    if not rel or rel.endswith("/"):
        rel += "index.html"
    f = ROOT / rel
    return f if f.exists() else None


def card_image(f: Path | None, url: str) -> str:
    """og:image, else the first real image in the page, as a site path."""
    if f is None:
        return ""
    s = BLOCK_RE.sub("", f.read_text(encoding="utf-8"))   # never pick up another post's card
    m = re.search(r'<meta[^>]+property="og:image"[^>]+content="([^"]+)"', s) or \
        re.search(r'<meta[^>]+content="([^"]+)"[^>]+property="og:image"', s)
    # og_tags.py gives image-less posts their topic's picture for link
    # previews; on a card that would just repeat, so it doesn't count here.
    cands = [m.group(1)] if m and "/images/features/topic-" not in m.group(1) else []
    body = s[s.find("<body"):]
    for im in re.finditer(r'<img[^>]+src="([^"]+)"', body):
        c = im.group(1)
        if not (c.startswith("data:") or c.endswith(".svg") or "favicon" in c or "badge" in c):
            cands.append(c)
    for c in cands:
        src = site_path(c, url)
        # a path on this site must exist here; other hosts (a sibling repo's
        # Pages site, raw.githubusercontent) are taken on trust
        if src.startswith("/") and not src.startswith("//"):
            rel = src.split("?")[0].lstrip("/")
            if not (ROOT / rel).exists() and not rel.startswith(SIBLING_REPOS):
                continue
        return src
    return ""


def site_path(src: str, url: str) -> str:
    # web_images.py serves WebP copies from /img-opt/<original>.w<N>.webp;
    # cards and previews name the original.
    m = re.match(r"(?:https://brooksgroves\.com)?/img-opt/(.+)\.w\d+\.webp$", src)
    if m:
        src = "/" + m.group(1)
    if src.startswith(SITE):
        src = src[len(SITE):]
    elif not src.startswith(("/", "http")):           # relative to the post
        base = local(url).rsplit("/", 1)[0]
        src = f"{base}/{src}"
        while "/../" in src:
            src = re.sub(r"/[^/]+/\.\./", "/", src, count=1)
        src = src.replace("/./", "/")
    return src


def pretty_date(iso: str) -> str:
    import datetime as dt
    try:
        d = dt.date.fromisoformat(iso)
    except ValueError:
        return iso                                   # "April 2026" and the like, as written
    return f"{d:%b} {d.day}, {d.year}"


def icon_of(title: str) -> str:
    m = re.match(r"^([^\w\"'“‘(]+)", title)
    return m.group(1).strip() if m else ""


def pick(post, pool, topic_id, topics, fallback, n=3):
    mine = set(post["tags"])
    same = [p for p in pool if p is not post and topic_of(p, topics, fallback) == topic_id]
    # most shared tags first, newest breaking ties
    same.sort(key=lambda p: (len(mine & set(p["tags"])), p["date"]), reverse=True)
    out = same[:n]
    for p in pool:                                   # POSTS is newest first
        if len(out) >= n:
            break
        if p is not post and p not in out:
            out.append(p)
    return out


def block(post, picks, topic, colors, imgs) -> str:
    cards = []
    for p in picks:
        img = imgs.get(p["url"], "")
        col = colors.get(p["url"], "var(--gold)")
        if img:
            media = (f'<img class="kr-img" src="{esc(img)}" alt="" loading="lazy" decoding="async">')
        else:
            media = (f'<span class="kr-img kr-noimg" style="--kr-c:{col}" aria-hidden="true">'
                     f'{esc(icon_of(p["title"]) or "✦")}</span>')
        cards.append(
            f'      <a class="kr-card" href="{esc(local(p["url"]))}">\n'
            f'        {media}\n'
            f'        <span class="kr-meta">{esc(pretty_date(p["date"]))}</span>\n'
            f'        <span class="kr-title">{esc(p["title"])}</span>\n'
            f'        <span class="kr-dek">{esc(p["dek"])}</span>\n'
            f'      </a>')
    more = ""
    if topic:
        more = (f'<a class="kr-more" href="/topics/{topic["id"]}/">More in {topic["icon"]} '
                f'{esc(topic["name"])} &rarr;</a>')
    return "\n".join([
        START,
        '<section class="keep-reading" aria-label="Keep reading">',
        '  <div class="kr-inner">',
        f'    <div class="kr-head"><h2 class="kr-label">Keep reading</h2>{more}</div>',
        '    <div class="kr-grid">',
        *cards,
        '    </div>',
        '  </div>',
        '</section>',
        END,
    ])


def insert(s: str, b: str) -> str:
    s = BLOCK_RE.sub("", s, count=1)
    i = s.find("\n<footer")
    if i < 0:
        m = re.search(r"\n[ \t]*<footer[\s>]", s)
        i = m.start() if m else -1
    if i < 0:
        m = re.search(r"\n[ \t]*<script[^>]+site-footer\.js", s)
        i = m.start() if m else s.rfind("</body>")
    return s[:i] + "\n\n" + b + "\n" + s[i:]


def build():
    cfg = json.loads((ROOT / "data/topics.json").read_text(encoding="utf-8"))
    topics, fallback = cfg["topics"], cfg.get("fallback", cfg["topics"][-1]["id"])
    by_id = {t["id"]: t for t in topics}
    hidden = tuple("https://" + h for h in cfg.get("exclude_hosts", []))
    skip = set(cfg.get("exclude_urls", []))
    pool = [p for p in posts() if not p["url"].startswith(hidden) and p["url"] not in skip]

    files = {p["url"]: page_file(p["url"]) for p in pool}
    imgs = {p["url"]: IMAGE_OVERRIDES.get(local(p["url"])) or card_image(files[p["url"]], p["url"])
            for p in pool}
    colors = {p["url"]: TOPIC_COLORS.get(topic_of(p, topics, fallback), "var(--gold)") for p in pool}

    changed = written = 0
    for p in pool:
        f = files[p["url"]]
        if f is None or "/blog/" not in p["url"]:
            continue                                  # only posts that live here
        t = topic_of(p, topics, fallback)
        b = block(p, pick(p, pool, t, topics, fallback), by_id.get(t), colors, imgs)
        s = f.read_text(encoding="utf-8")
        s2 = insert(s, b)
        written += 1
        if s2 != s:
            f.write_text(s2, encoding="utf-8")
            changed += 1
    with_img = sum(1 for v in imgs.values() if v)
    print(f"keep reading: {written} posts, {changed} changed | images for {with_img}/{len(pool)} posts")


if __name__ == "__main__":
    build()
